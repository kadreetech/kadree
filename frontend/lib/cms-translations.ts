export function spanishContent<T>(value: T): T {
  if (typeof value === 'string') {
    const normalized = value.replace(/\u00a0/g, ' ').trim()
    const translated = translations[normalized]
    if (!translated) return value
    const leading = value.match(/^\s*/)?.[0] || ''
    const trailing = value.match(/\s*$/)?.[0] || ''
    return (leading + translated + trailing) as T
  }
  if (Array.isArray(value)) return value.map(spanishContent) as T
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, spanishContent(item)])) as T
  }
  return value
}
